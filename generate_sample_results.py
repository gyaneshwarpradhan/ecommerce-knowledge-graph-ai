"""
generate_sample_results.py

Run all 6 sample questions against the real implementation and write actual
outputs to results/sample_results.md.

Usage:
    python generate_sample_results.py
"""

from __future__ import annotations

import io
import json
import sys
import time
from pathlib import Path

# Ensure UTF-8 stdout on Windows
if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if sys.stderr and hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

sys.path.insert(0, str(Path(__file__).resolve().parent))

from dotenv import load_dotenv

load_dotenv()

from src.graph import KnowledgeGraph
from src.llm import generate_answer, generate_query, validate_query
from src.retriever import Retriever

DATA_PATH = Path("data/ecommerce_data.json")
OUTPUT_PATH = Path("results/sample_results.md")

SAMPLE_QUESTIONS = [
    "Which products from Nike are supplied by ABC Sports?",
    "What products belong to the Shoes category?",
    "What products did Rahul Sharma order?",
    "Which products are supplied by Tech World?",
    "Find banana in the knowledge graph.",
    "What is the price of iPhone 99?",
]


def run_question(question: str, retriever: Retriever) -> dict:
    """Run one question through the full pipeline and return a result dict."""
    structured_query = generate_query(question)
    is_valid, error = validate_query(structured_query)

    if not is_valid:
        return {
            "question": question,
            "structured_query": structured_query,
            "validation": f"INVALID: {error}",
            "retrieved_data": None,
            "answer": "I couldn't map your question to a supported operation.",
        }

    operation = structured_query.get("operation", "")
    if operation == "unsupported":
        return {
            "question": question,
            "structured_query": structured_query,
            "validation": "VALID (unsupported operation)",
            "retrieved_data": None,
            "answer": "I couldn't find this information in the knowledge graph.",
        }

    retrieved_data = retriever.execute(structured_query)
    answer = generate_answer(question, retrieved_data)

    return {
        "question": question,
        "structured_query": structured_query,
        "validation": "VALID",
        "retrieved_data": retrieved_data,
        "answer": answer,
    }


def build_markdown(results: list[dict]) -> str:
    lines = [
        "# Sample Results",
        "",
        "Actual outputs generated by running the application against the real knowledge graph with Gemini LLM.",
        "No outputs are fabricated — these are live results from the pipeline.",
        "",
        "---",
        "",
    ]

    for i, r in enumerate(results, 1):
        lines += [
            f"## Question {i}",
            "",
            f"**Q:** {r['question']}",
            "",
            "**Structured Query (LLM Call #1 - Gemini):**",
            "```json",
            json.dumps(r["structured_query"], indent=2),
            "```",
            "",
            f"**Validation:** {r['validation']}",
            "",
            "**Retrieved Graph Data:**",
            "```json",
            json.dumps(r["retrieved_data"], indent=2, ensure_ascii=False)
            if r["retrieved_data"] is not None
            else "(no data retrieved)",
            "```",
            "",
            "**Answer (LLM Call #2 - Gemini):**",
            "",
            r["answer"],
            "",
            "---",
            "",
        ]

    return "\n".join(lines)


def main() -> None:
    print("Loading knowledge graph...")
    kg = KnowledgeGraph(DATA_PATH)
    retriever = Retriever(kg)
    print(f"Graph loaded: {kg.stats()}")

    banana_count = kg.validate_banana_count()
    print(f"Banana validation: {banana_count} banana nodes found [OK]")

    results = []
    for i, q in enumerate(SAMPLE_QUESTIONS, 1):
        print(f"\n[{i}/{len(SAMPLE_QUESTIONS)}] Running: {q!r}")
        result = run_question(q, retriever)
        results.append(result)
        print(f"  -> Answer: {result['answer'][:120]}...")
        # Brief pause between questions to respect free tier rate limits
        if i < len(SAMPLE_QUESTIONS):
            time.sleep(6.0)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(build_markdown(results), encoding="utf-8")
    print(f"\n[OK] Results written to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
